'use strict';

// Generates lib/glyphs.js from the Bravura font (SMuFL, SIL OFL 1.1).
//
//   git clone --depth 1 --branch bravura-1.482 https://github.com/steinbergmedia/bravura.git /tmp/bravura
//   npm install --prefix /tmp/glyph-tools opentype.js
//   NODE_PATH=/tmp/glyph-tools/node_modules node scripts/extract-glyphs.js /tmp/bravura > lib/glyphs.js
//
// Only the glyphs listed below are kept. Coordinates are in staff spaces (one
// quarter of an em), y down, origin at the SMuFL glyph origin.
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const opentype = require('opentype.js');

const dir = path.resolve(process.argv[2] || '.');
const raw = fs.readFileSync(path.join(dir, 'redist', 'otf', 'Bravura.otf'));
const font = opentype.parse(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength));
const meta = JSON.parse(fs.readFileSync(path.join(dir, 'redist', 'Bravura.json'), 'utf8'));

// SMuFL code points (the font ships without glyph names). Each outline is
// checked against the bounding box in Bravura.json, so a wrong code point fails.
const codepoints = {
  unpitchedPercussionClef1: 0xE069,
  noteheadHalf: 0xE0A3, noteheadBlack: 0xE0A4, noteheadXBlack: 0xE0A9, noteheadDiamondBlack: 0xE0DB,
  noteheadParenthesisLeft: 0xE0F5, noteheadParenthesisRight: 0xE0F6,
  flag8thUp: 0xE240, flag8thDown: 0xE241, flag16thUp: 0xE242, flag16thDown: 0xE243,
  flag32ndUp: 0xE244, flag32ndDown: 0xE245,
  restWhole: 0xE4E3, restHalf: 0xE4E4, restQuarter: 0xE4E5, rest8th: 0xE4E6, rest16th: 0xE4E7, rest32nd: 0xE4E8,
  articAccentAbove: 0xE4A0, articAccentBelow: 0xE4A1
};
for (let d = 0; d < 10; d++) codepoints['timeSig' + d] = 0xE080 + d;
const names = Object.keys(codepoints);

const round = n => Math.round(n * 1000) / 1000;

const glyphs = {};
names.forEach(name => {
  const g = font.charToGlyph(String.fromCodePoint(codepoints[name]));
  // font size 4 makes one em equal four staff spaces
  const p = g.getPath(0, 0, 4);
  const d = p.toPathData(3).replace(/(\.\d*?)0+(?=\D|$)/g, '$1').replace(/\.(?=\D|$)/g, '');
  const box = meta.glyphBBoxes[name];
  const bb = p.getBoundingBox();
  const want = [box.bBoxSW[0], -box.bBoxNE[1], box.bBoxNE[0], -box.bBoxSW[1]];
  [bb.x1, bb.y1, bb.x2, bb.y2].forEach((v, i) => {
    if (Math.abs(v - want[i]) > 0.02) throw new Error('code point does not match ' + name);
  });
  const a = meta.glyphsWithAnchors[name] || {};
  const out = { w: round(meta.glyphAdvanceWidths[name]), d };
  if (box) out.box = [box.bBoxSW[0], -box.bBoxNE[1], box.bBoxNE[0], -box.bBoxSW[1]].map(round);
  if (a.stemUpSE) out.up = [a.stemUpSE[0], -a.stemUpSE[1]].map(round);
  if (a.stemDownNW) out.down = [a.stemDownNW[0], -a.stemDownNW[1]].map(round);
  glyphs[name] = out;
});

const commit = execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const tag = execFileSync('git', ['-C', dir, 'describe', '--tags', '--exact-match'], { encoding: 'utf8' }).trim();

const lines = Object.keys(glyphs).map(n => '  ' + n + ': ' + JSON.stringify(glyphs[n]).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'"));
process.stdout.write(`'use strict';

// Generated by scripts/extract-glyphs.js. Do not edit.
// Glyph outlines from the Bravura music font (SMuFL), copyright 2026 Steinberg
// Media Technologies GmbH, licensed under the SIL Open Font License 1.1.
// See NOTICE-BRAVURA.txt. Source: ${tag}, commit ${commit}.
//
// Units are staff spaces, y down, origin at the SMuFL glyph origin. w is the
// advance, box is [left, top, right, bottom], up and down are the stem anchors
// (stem up at the right edge, stem down at the left edge).
module.exports = {
${lines.join(',\n')}
};
`);
